#include <stdio.h>
int main()
{
	int a = 20;
	int b = 10;

	int sum = a + b;
	int product = a * b;
	int divide = a / b;
	int difference = a - b;

	printf("The Sum is = %d\n",sum);
	printf("The product is = %d\n",product);
	printf("The quotient is = %d\n",divide);
	printf("The difference is = %d\n",difference);

	return 0;
}
